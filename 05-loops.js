// 1. Standard For Loop (great for counting)
console.log("--- For Loop ---");
for (let i = 1; i <= 3; i++) {
    console.log("Count number:", i);
}

// 2. Loop through an array
let techStack = ["HTML", "CSS", "JS", "C++"];
console.log("--- Array Loop ---");
for (let index = 0; index < techStack.length; index++) {
    console.log("Tech:", techStack[index]);
}